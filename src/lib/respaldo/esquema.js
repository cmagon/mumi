// Generador del ESQUEMA (SQL) a partir del catálogo que devuelve respaldo_catalogo() (migración v184).
// JS puro (sin dependencias del navegador) para poder probarse en Node.
//
// Se genera desde la base VIVA, no desde los archivos del repositorio: así el proyecto nuevo queda
// idéntico a como está hoy el de origen (aunque alguna migración se haya aplicado distinto).
//
// Partes (cada una es un script independiente, para pegar en el SQL Editor en este orden):
//   01 extensiones, tipos y secuencias · 02 tablas · 03 llaves y restricciones · 04 llaves foráneas e índices
//   05 funciones, vistas y triggers    · 06 permisos, RLS y Storage

export const q = (s) => '"' + String(s).replace(/"/g, '""') + '"'
const lit = (s) => (s == null ? 'null' : "'" + String(s).replace(/'/g, "''") + "'")
const ROLES_OK = new Set(['public', 'anon', 'authenticated', 'service_role'])
const PRIV_OK = new Set(['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER'])
const rolSql = (r) => (r === 'public' ? 'public' : q(r))

// Orden de creación de tablas por llaves foráneas (las referenciadas primero). Los ciclos van al final.
export function ordenarTablasPorFk(catalogo) {
  const tablas = catalogo.tablas || []
  const nombres = new Set(tablas.map(t => t.nombre))
  const deps = new Map(tablas.map(t => [t.nombre, new Set((t.restricciones || []).filter(r => r.tipo === 'f' && r.ref_tabla && r.ref_tabla !== t.nombre && nombres.has(r.ref_tabla)).map(r => r.ref_tabla))]))
  const orden = [], hechas = new Set()
  let progreso = true
  while (hechas.size < tablas.length && progreso) {
    progreso = false
    for (const t of tablas) {
      if (hechas.has(t.nombre)) continue
      if ([...deps.get(t.nombre)].every(d => hechas.has(d))) { orden.push(t.nombre); hechas.add(t.nombre); progreso = true }
    }
  }
  for (const t of tablas) if (!hechas.has(t.nombre)) orden.push(t.nombre)   // ciclos
  return orden
}

const defColumna = (c) => {
  let s = `${q(c.nombre)} ${c.tipo}`
  if (c.generada) s += ` generated always as (${c.generada}) stored`
  else if (c.identidad === 'a') s += ' generated always as identity'
  else if (c.identidad === 'd') s += ' generated by default as identity'
  else if (c.defecto != null) s += ` default ${c.defecto}`
  if (c.no_nulo) s += ' not null'
  return s
}

const hacerDo = (sentencias) => `do $$ begin\n${sentencias.map(x => `  begin ${x}; exception when duplicate_object or duplicate_table or invalid_table_definition then null; end;`).join('\n')}\nend $$;`

function grantsTabla(t, objeto = 'table') {
  const out = []
  const nom = `public.${q(t.nombre)}`
  if (!t.acl_definida) return out
  out.push(`revoke all on ${objeto} ${nom} from public, anon, authenticated, service_role;`)
  for (const a of t.acl || []) {
    if (!ROLES_OK.has(a.rol)) continue
    const pr = (a.priv || []).filter(p => PRIV_OK.has(p))
    if (pr.length) out.push(`grant ${pr.join(', ').toLowerCase()} on ${objeto} ${nom} to ${rolSql(a.rol)};`)
  }
  // Permisos por columna (p. ej. alegra_config.token no legible desde el navegador)
  const grupos = new Map()
  for (const a of t.acl_cols || []) {
    if (!ROLES_OK.has(a.rol)) continue
    const pr = (a.priv || []).filter(p => ['SELECT', 'INSERT', 'UPDATE', 'REFERENCES'].includes(p)).join(',')
    if (!pr) continue
    const k = `${a.rol}|${pr}`
    if (!grupos.has(k)) grupos.set(k, { rol: a.rol, pr, cols: [] })
    grupos.get(k).cols.push(a.col)
  }
  for (const g of grupos.values()) {
    const cols = g.cols.map(q).join(', ')
    out.push(`grant ${g.pr.split(',').map(p => `${p.toLowerCase()} (${cols})`).join(', ')} on ${objeto} ${nom} to ${rolSql(g.rol)};`)
  }
  return out
}

export function generarEsquemaSql(cat, { origen = '' } = {}) {
  const cab = (n, titulo) => `-- ============================================================\n-- MUMI — Esquema ${n}/6: ${titulo}\n-- Generado: ${cat.generado || ''}${origen ? `\n-- Origen: ${origen}` : ''}\n-- Ejecutar en el SQL Editor del proyecto NUEVO, en orden (01 → 06). Es repetible (idempotente).\n-- ============================================================\nset check_function_bodies = false;\nset client_min_messages = warning;\n`
  const partes = []

  // ── 01 extensiones, tipos, secuencias ───────────────────────────────────────
  {
    const l = [cab(1, 'extensiones, tipos y secuencias')]
    for (const e of cat.extensiones || []) {
      if (['plpgsql'].includes(e.nombre)) continue
      const con = e.esquema === 'extensions' ? ' with schema extensions' : ''
      l.push(`do $$ begin create extension if not exists ${q(e.nombre)}${con}; exception when others then raise notice 'No se pudo habilitar la extensión ${e.nombre}: %. Habilítala en Database → Extensions.', sqlerrm; end $$;`)
    }
    for (const t of cat.tipos || []) {
      l.push(`do $$ begin if not exists (select 1 from pg_type where typname = ${lit(t.nombre)} and typnamespace = 'public'::regnamespace) then create type public.${q(t.nombre)} as enum (${(t.valores || []).map(lit).join(', ')}); end if; end $$;`)
    }
    for (const s of cat.secuencias || []) {
      l.push(`create sequence if not exists public.${q(s.nombre)} as ${s.tipo} increment by ${s.incremento} minvalue ${s.minimo} maxvalue ${s.maximo} start with ${s.inicio}${s.ciclo ? ' cycle' : ''};`)
    }
    partes.push({ n: '01', nombre: 'extensiones_tipos_secuencias', sql: l.join('\n') + '\n' })
  }

  // ── 02 tablas (sin restricciones: se agregan después, en cualquier orden) ───
  {
    const l = [cab(2, 'tablas')]
    for (const nom of ordenarTablasPorFk(cat)) {
      const t = cat.tablas.find(x => x.nombre === nom)
      l.push(`create table if not exists public.${q(t.nombre)} (\n  ${(t.columnas || []).map(defColumna).join(',\n  ')}\n);`)
    }
    for (const s of cat.secuencias || []) if (s.tabla && s.columna) l.push(`alter sequence public.${q(s.nombre)} owned by public.${q(s.tabla)}.${q(s.columna)};`)
    partes.push({ n: '02', nombre: 'tablas', sql: l.join('\n') + '\n' })
  }

  // ── 03 llaves primarias, únicas y CHECK ────────────────────────────────────
  {
    const l = [cab(3, 'llaves primarias, únicas y restricciones CHECK')]
    for (const t of cat.tablas) {
      const sent = (t.restricciones || []).filter(r => ['p', 'u', 'c', 'x'].includes(r.tipo)).map(r => `alter table public.${q(t.nombre)} add constraint ${q(r.nombre)} ${r.def}`)
      if (sent.length) l.push(hacerDo(sent))
    }
    partes.push({ n: '03', nombre: 'restricciones', sql: l.join('\n') + '\n' })
  }

  // ── 04 llaves foráneas e índices ───────────────────────────────────────────
  {
    const l = [cab(4, 'llaves foráneas e índices')]
    for (const nom of ordenarTablasPorFk(cat)) {
      const t = cat.tablas.find(x => x.nombre === nom)
      const sent = (t.restricciones || []).filter(r => r.tipo === 'f').map(r => `alter table public.${q(t.nombre)} add constraint ${q(r.nombre)} ${r.def}`)
      if (sent.length) l.push(hacerDo(sent))
    }
    for (const t of cat.tablas) for (const ix of t.indices || []) {
      l.push(String(ix.def).replace(/^CREATE (UNIQUE )?INDEX /i, (m, u) => `CREATE ${u || ''}INDEX IF NOT EXISTS `) + ';')
    }
    partes.push({ n: '04', nombre: 'foraneas_indices', sql: l.join('\n') + '\n' })
  }

  // ── 05 funciones, vistas, triggers ─────────────────────────────────────────
  {
    const l = [cab(5, 'funciones, vistas y triggers')]
    for (const f of cat.funciones || []) l.push(String(f.def).trim().replace(/;?$/, ';'))
    for (const v of cat.vistas || []) l.push(`create or replace ${v.materializada ? 'materialized ' : ''}view public.${q(v.nombre)} as\n${String(v.def).trim().replace(/;?$/, '')};`.replace('create or replace materialized view', 'create materialized view if not exists'))
    for (const t of cat.tablas) for (const tg of t.triggers || []) {
      l.push(`drop trigger if exists ${q(tg.nombre)} on public.${q(t.nombre)};`)
      l.push(String(tg.def).trim().replace(/;?$/, ';'))
    }
    partes.push({ n: '05', nombre: 'funciones_vistas_triggers', sql: l.join('\n') + '\n' })
  }

  // ── 06 permisos, RLS, políticas y Storage ──────────────────────────────────
  {
    const l = [cab(6, 'permisos, seguridad por fila (RLS) y Storage')]
    for (const t of cat.tablas) l.push(...grantsTabla(t))
    for (const v of cat.vistas || []) l.push(...grantsTabla(v, 'table'))
    for (const f of cat.funciones || []) {
      if (!f.acl_definida) continue
      const sig = `public.${q(f.nombre)}(${f.args})`
      l.push(`revoke all on function ${sig} from public, anon, authenticated, service_role;`)
      const roles = (f.acl || []).filter(a => ROLES_OK.has(a.rol) && (a.priv || []).includes('EXECUTE')).map(a => rolSql(a.rol))
      if (roles.length) l.push(`grant execute on function ${sig} to ${roles.join(', ')};`)
    }
    for (const t of cat.tablas) {
      if (t.rls) l.push(`alter table public.${q(t.nombre)} enable row level security;`)
      if (t.rls_forzado) l.push(`alter table public.${q(t.nombre)} force row level security;`)
    }
    for (const p of cat.politicas || []) {
      const tabla = `${p.esquema}.${q(p.tabla)}`
      const roles = (p.roles || []).length ? ` to ${p.roles.map(r => (r === 'public' ? 'public' : q(r))).join(', ')}` : ''
      l.push(`drop policy if exists ${q(p.nombre)} on ${tabla};`)
      l.push(`create policy ${q(p.nombre)} on ${tabla} as ${String(p.permisiva).toLowerCase() === 'restrictive' ? 'restrictive' : 'permissive'} for ${String(p.cmd).toLowerCase()}${roles}${p.usando != null ? ` using (${p.usando})` : ''}${p.con_check != null ? ` with check (${p.con_check})` : ''};`)
    }
    for (const b of cat.buckets || []) {
      const mime = Array.isArray(b.mime) && b.mime.length ? `array[${b.mime.map(lit).join(', ')}]::text[]` : 'null'
      l.push(`insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (${lit(b.id)}, ${lit(b.nombre)}, ${b.publico ? 'true' : 'false'}, ${b.limite == null ? 'null' : Number(b.limite)}, ${mime})\n  on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;`)
    }
    partes.push({ n: '06', nombre: 'permisos_rls_storage', sql: l.join('\n') + '\n' })
  }

  const completo = partes.map(p => p.sql).join('\n')
  return { completo, partes }
}

// ── Utilidades de datos ───────────────────────────────────────────────────────
// Reemplaza la URL base del proyecto viejo por la del nuevo en cualquier texto (URLs de Storage guardadas en filas)
export function reemplazarUrls(texto, desde, hasta) {
  if (!desde || !hasta || desde === hasta) return texto
  return String(texto).split(desde).join(hasta)
}

// Parte un arreglo de filas en bloques de ~maxBytes (para no exceder el tamaño de una llamada)
export function trocearFilas(filas, maxBytes = 1_500_000) {
  const bloques = []
  let actual = [], tam = 0
  for (const f of filas) {
    const n = JSON.stringify(f).length
    if (actual.length && (tam + n > maxBytes || actual.length >= 1000)) { bloques.push(actual); actual = []; tam = 0 }
    actual.push(f); tam += n
  }
  if (actual.length) bloques.push(actual)
  return bloques
}

// Datos que no deben viajar en el respaldo
export function limpiarFilaSensible(tabla, fila) {
  if (tabla === 'alegra_config' && 'token' in fila) return { ...fila, token: null }   // el token se vuelve a configurar en el destino
  return fila
}
